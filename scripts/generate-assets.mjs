import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const assetsDir = join(root, "assets");
const outDir = join(root, "src", "generated");

const files = [
  { name: "highchartsJs", file: "highcharts.js" },
  { name: "timelineJs", file: "timeline.js" },
];

let output = `// Auto-generated by scripts/generate-assets.mjs\n// DO NOT EDIT DIRECTLY\n\n`;

for (const { name, file } of files) {
  const content = readFileSync(join(assetsDir, file), "utf-8");
  output += `const ${name} = ${JSON.stringify(content)};\n`;
}

output += `\nexport { ${files.map((f) => f.name).join(", ")} };\n`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "assets.ts"), output, "utf-8");

console.log("Generated src/generated/assets.ts");
